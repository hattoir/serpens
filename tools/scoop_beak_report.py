def wil(k: int, n: int) -> tuple[float, float]:
    if n == 0:
        return 0.0, 1.0
    p = k / n
    den = 1 + Z90 * Z90 / n
    mid = (p + Z90 * Z90 / (2 * n)) / den
    h = Z90 * math.sqrt(p * (1 - p) / n + Z90 * Z90 / (4 * n * n)) / den
    return max(0.0, mid - h), min(1.0, mid + h)


def load(name: str) -> list[dict]:
    return list(csv.DictReader(open(RES / f"scoop_beak_{name}_designs.csv", encoding="utf-8")))


def isum(rs: list[dict], key: str) -> int:
    return sum(int(float(r[key])) for r in rs)


def frac(k: int, n: int, ci: bool = False) -> str:
    if n == 0:
        return "-"
    if ci:
        lo, hi = wil(k, n)
        return f"{100 * k / n:.0f}% ({k}/{n}, {100 * lo:.0f}–{100 * hi:.0f}%)"
    return f"{100 * k / n:.0f}% ({k}/{n})"


def pooled_row(label: str, rs: list[dict]) -> str:
    n = isum(rs, "n")
    return (f"| {label} | {n} | {frac(isum(rs, 'n_rode'), n)} | {frac(isum(rs, 'n_entered'), n)} | {frac(isum(rs, 'successes'), n)} | "
            f"{frac(isum(rs, 'n_success_clean'), n)} | {frac(isum(rs, 'n_launched'), n)} |")


